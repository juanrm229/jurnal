/** Kepala + bahu. */
function person(p: Pen, cx: number, headY: number, r: number, shoulderY: number, w: number): void {
  p.circle(cx, headY, r);
  p.curve(
    [
      [cx - w, shoulderY + w * 0.55],
      [cx - w * 0.85, shoulderY + w * 0.1],
      [cx - w * 0.45, shoulderY - w * 0.25],
      [cx, shoulderY - w * 0.32],
      [cx + w * 0.45, shoulderY - w * 0.25],
      [cx + w * 0.85, shoulderY + w * 0.1],
      [cx + w, shoulderY + w * 0.55],
    ],
    { wob: 0.25 },
  );
}

function flame(p: Pen, cx: number, top: number, bottom: number, w: number): void {
  const h = bottom - top;
  const X = (f: number): number => cx + w * f;
  const Y = (f: number): number => top + h * f;
  p.curve(
    [
      [X(0.05), Y(0), 1],
      [X(-0.45), Y(0.3)],
      [X(-0.95), Y(0.55)],
      [X(-0.9), Y(0.82)],
      [X(-0.45), Y(0.98)],
      [X(0.1), Y(1)],
      [X(0.65), Y(0.93)],
      [X(0.95), Y(0.7)],
      [X(0.9), Y(0.45)],
      [X(0.62), Y(0.28), 1],
      [X(0.48), Y(0.45)],
      [X(0.4), Y(0.22)],
      [X(0.05), Y(0)],
    ],
    { wob: 0.25 },
  );
}

function arrowH(p: Pen, dir: 1 | -1): void {
  const tip = dir > 0 ? 52 : 12;
  p.line(dir > 0 ? 12 : 52, 32, tip, 32, 0.3);
  p.poly(
    [
      [tip - dir * 13, 19.5],
      [tip, 32],
      [tip - dir * 13, 44.5],
    ],
    false,
    0.3,
  );
}

